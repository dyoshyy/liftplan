-- ログインの土台。アカウント（誰か）とセッション（ログイン中の端末）。
--
-- ここではまだ誰も使わない。ルートも配線も別のPRで入る。

-- アカウント。プロバイダ側の不変な識別子と UserID の対応。
--
-- (provider, subject) を主キーにするのが要。これが無いと、コールバックが
-- 同時に2回来たときに同じ人のアカウントが2つでき、ログインのたびに違う
-- UserID が返って記録が2人分に割れる。アプリ側の「引いて、無ければ作る」は
-- 2つの文に分かれるので、その間に割り込まれる余地が必ずある。
--
-- 同じ人が GitHub と Google の両方で入ったら別人になる（名寄せはしない）。
-- subject は GitHub の数値ID・Google の sub で、どちらも本人には変えられない。
-- メールやユーザー名で突き合わせると、向こう側で差し替えられたときに
-- 他人の記録へ入れてしまう。
CREATE TABLE accounts (
    provider text NOT NULL,
    subject  text NOT NULL,
    user_id  uuid NOT NULL,
    PRIMARY KEY (provider, subject)
);

-- セッション。トークンそのものは保存しない。
--
-- 入るのは SHA-256 のハッシュだけ。DB が漏れてもセッションは漏れない
-- （ハッシュから元のトークンは作れない）。引くのもハッシュなので、
-- 主キーの索引がそのまま使え、定数時間比較も要らない。
--
-- user_id を accounts 経由にせず直接持つのは、セッションを引くたびに
-- 結合する理由が無いため。認証はリクエストごとに走る。
--
-- 外部キーは張らない。理由は2つある。
--   1. 参照先が無い。accounts の主キーは (provider, subject) なので
--      user_id は一意でなく、users のような表もこの時点では存在しない
--   2. user_id を持つ他の表（set_logs など）は 0007 の担当で、
--      このPRでは触らない
-- 参照整合が要るなら users 表を作る話になる。いまは「アカウントを消す」
-- 経路自体が無いので、孤児の行は生まれない。必要になってから作る。
--
-- 期限切れの行を掃除する仕組みも入れない。Find が期限で弾くので、
-- 残っていても有効にはならない。溜まって困る量になってから考える。
CREATE TABLE sessions (
    token_hash text        PRIMARY KEY,
    user_id    uuid        NOT NULL,
    expires_at timestamptz NOT NULL
);
