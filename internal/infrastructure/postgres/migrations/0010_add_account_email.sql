-- アカウントに確認済みのメールアドレスを持たせる。
--
-- GitHub と Google でログインすると別のアカウントになる。主キーが
-- (provider, subject) で、両者は別の名前空間だから。これを確認済みの
-- メールアドレスで結ぶための、置き場を作る。
--
-- **結ぶ判断はこのマイグレーションの担当ではない。**ここで作るのは列だけで、
-- 「同じアドレスなら同じ人とみなす」を決めるのは別のPR。
--
-- 0008 は「メールで突き合わせると、向こう側で差し替えられたときに他人の
-- 記録へ入れてしまう」として、この列を置かないことにしていた。**確認済みの
-- ものに限る**ことでその危険は避けられるので、方針を変える。適用済みの
-- 0008 は書き換えられないため、経緯をここに書く。
ALTER TABLE accounts ADD COLUMN email text;


-- NOT NULL にしない理由 -------------------------------------------------
--
-- 既にある行は、当時アドレスを取っていないので入れる値が無い。NOT NULL に
-- するなら空文字を埋めることになるが、空文字は「アドレスが無い」ではなく
-- 「空という値のアドレス」として引く側に当たりうる。全員が同じ空文字を
-- 持つと、アドレスを持たない利用者が全員同一人物になる。
--
-- 取れなかったことは NULL で表す。新しい行も、プロバイダがアドレスを
-- 返さなければ NULL で入る（Go 側が空文字を NULLIF で落とす）。


-- 一意制約を付けない理由 -----------------------------------------------
--
-- **同じアドレスの行が2つあるのが正常。**同じ人が GitHub と Google の
-- 両方で入れば、同じアドレスを持つ行が2つできる。それこそが結びたい形で、
-- 一意制約を付けると2つめのログインが一意制約違反で落ちる。
--
-- では「違う人が同じアドレスを持つ」ことを何が防ぐか。防がない。DB は
-- 一意性を保証できる位置にいない（確認済みかどうかを知らない）ので、
-- 2人ぶら下がっている状態は**引くときに検出して、結ばない**ことにした。
-- 一意制約で弾くと、後から入った本人がログインできなくなる。


-- 索引を付けない理由 ---------------------------------------------------
--
-- この表は利用者1人につき多くても2行（GitHub と Google）しか持たない。
-- 数千行の順次走査はミリ秒に満たず、引くのもログインのときだけ。
--
