// newId はセットの ID をクライアントで採番する。
//
// サーバーに採番させると、応答を受け取るまで手元の記録に ID が無い。
// 圏外で記録したものを直したり取り消したりできなくなる。
// クライアントが採番すれば、送信の成否と関係なく記録を指せる。
//
// 衝突しても実害が出ないのは、サーバーが冪等だから（同じ ID の同じ内容は
// 成功、内容違いは 409）。それでも時刻とランダムを混ぜて避ける。
export function newId(): string {
  return `w-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}
